    public static readonly string[] Supported = [English, Spanish, Portuguese, German, French, Polish, Russian, Romanian];

    private static volatile string _language = English;

    /// <summary>Current language; unknown values fall back to English.</summary>
    public static string Language
    {
        get => _language;
        set => _language = Normalize(value);
    }

    /// <summary>Maps regional codes (pt-BR, de-AT) onto a supported language; anything else is English.</summary>
    public static string Normalize(string? value)
    {
        var code = value?.Trim().ToLowerInvariant().Split('-', '_')[0];
        return code is not null && Supported.Contains(code) ? code : English;
    }

    /// <summary>True when <paramref name="value"/> names a supported language, alone or with a region.</summary>
    public static bool IsSupported(string? value)
    {
        var code = value?.Trim().ToLowerInvariant().Split('-', '_')[0];
        return code is not null && Supported.Contains(code);
    }

    /// <summary>Text for <paramref name="key"/> in the current language (English, then the key, as fallback).</summary>
    public static string T(string key, params object?[] args) => TIn(_language, key, args);

    public static string TIn(string language, string key, params object?[] args)
    {
        if (!Table(language).TryGetValue(key, out var text) && !En.TryGetValue(key, out text)) text = key;
        return args.Length == 0 ? text : string.Format(CultureInfo.InvariantCulture, text, args);
    }

    public static IReadOnlyDictionary<string, string> Table(string language) => language switch
    {
        Romanian => Ro,
        Spanish => Es,
        Portuguese => Pt,
        German => De,
        French => Fr,
        Polish => Pl,
        Russian => Ru,
        _ => En,
    };

